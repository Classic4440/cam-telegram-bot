            ('reminders', 'text', 'text', 'NO', null),
            ('reminders', 'due_at', 'timestamp with time zone', 'NO', null),
            ('reminders', 'sent', 'boolean', 'NO', null)
        ) as cols(table_name, column_name, data_type, is_nullable, generated)
    loop
        select c.data_type, c.is_nullable, c.column_default, c.is_identity
          into actual_type, actual_nullable, actual_default, actual_identity
          from information_schema.columns c
         where c.table_schema = 'public'
           and c.table_name = expected.table_name
           and c.column_name = expected.column_name;

        if not found then
            raise exception 'Persistence migration stopped: public.%.% is missing',
