-- Additive persistence contract used by bot/store.py.
-- Run as the Supabase project database owner from SQL Editor or psql.
-- Existing tables are preserved; incompatible existing layouts abort validation below.

create table if not exists public.profiles (
    user_id bigint primary key,
    username text,
    xp bigint not null default 0,
    persona text not null default 'default',
    timezone text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.profiles
    add column if not exists username text,
    add column if not exists xp bigint not null default 0,
    add column if not exists persona text not null default 'default',
    add column if not exists timezone text,
    add column if not exists created_at timestamptz not null default now(),
    add column if not exists updated_at timestamptz not null default now();

create table if not exists public.notes (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    body text not null check (char_length(body) <= 1000),
    created_at timestamptz not null default now()
);

create table if not exists public.user_profiles (
    user_id bigint primary key,
    profile_data text not null default '',
    updated_at timestamptz not null default now()
);

create table if not exists public.chat_history (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.todos (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    text text not null,
    done boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.reminders (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    chat_id bigint not null,
    text text not null,
    due_at timestamptz not null,
    sent boolean not null default false
);

-- ON CONFLICT in the callers and stable row identifiers require unique keys.
-- Index creation fails safely (without deleting rows) if existing data violates them.
create unique index if not exists profiles_pkey on public.profiles (user_id);
create unique index if not exists notes_pkey on public.notes (id);
create unique index if not exists user_profiles_pkey on public.user_profiles (user_id);
create unique index if not exists chat_history_pkey on public.chat_history (id);
create unique index if not exists todos_pkey on public.todos (id);
create unique index if not exists reminders_pkey on public.reminders (id);
create index if not exists notes_user_id_id_idx on public.notes (user_id, id);
create index if not exists chat_history_user_created_idx
    on public.chat_history (user_id, created_at desc, id desc);
create index if not exists todos_user_id_id_idx on public.todos (user_id, id);
create index if not exists reminders_pending_due_idx on public.reminders (due_at) where sent = false;
create index if not exists reminders_user_due_idx on public.reminders (user_id, due_at) where sent = false;

