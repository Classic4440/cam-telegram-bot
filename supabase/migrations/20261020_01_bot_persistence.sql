-- RLS remains enabled for private data; only the trusted server-side role gets table access.
-- service_role is not exposed to Telegram users and bypasses RLS by design.
alter table public.profiles enable row level security;
alter table public.notes enable row level security;
alter table public.user_profiles enable row level security;
alter table public.chat_history enable row level security;
alter table public.todos enable row level security;
alter table public.reminders enable row level security;

-- Remove the broad service_role policies from the earlier bootstrap SQL.
-- service_role bypasses RLS; no permissive policy is needed for it.
drop policy if exists profiles_service_role_all on public.profiles;
drop policy if exists notes_service_role_all on public.notes;

revoke all on public.profiles, public.notes, public.user_profiles,
    public.chat_history, public.todos, public.reminders
    from public, anon, authenticated;
grant select, insert, update, delete on public.profiles, public.notes,
    public.user_profiles, public.chat_history, public.todos, public.reminders
    to service_role;

do $$
declare
    sequence_record record;
begin
    for sequence_record in
        select sequence_namespace.nspname as schema_name, sequence_relation.relname as sequence_name
          from pg_class sequence_relation
          join pg_namespace sequence_namespace on sequence_namespace.oid = sequence_relation.relnamespace
          join pg_depend dependency on dependency.objid = sequence_relation.oid
          join pg_class table_relation on table_relation.oid = dependency.refobjid
          join pg_namespace table_namespace on table_namespace.oid = table_relation.relnamespace
          join pg_attribute id_column
            on id_column.attrelid = table_relation.oid
           and id_column.attnum = dependency.refobjsubid
         where sequence_relation.relkind = 'S'
           and dependency.deptype in ('a', 'i')
           and table_namespace.nspname = 'public'
           and table_relation.relname in ('notes', 'chat_history', 'todos', 'reminders')
           and id_column.attname = 'id'
    loop
        execute format(
            'grant usage, select on sequence %I.%I to service_role',
            sequence_record.schema_name,
            sequence_record.sequence_name
        );
    end loop;
end;
$$;

do $$
declare
    target_oid oid := to_regprocedure('public.add_xp(bigint,text,integer)');
    arg_names text[];
begin
    if exists (
        select 1
          from pg_proc p
          join pg_namespace n on n.oid = p.pronamespace
         where n.nspname = 'public'
           and p.proname = 'add_xp'
           and (target_oid is null or p.oid <> target_oid)
    ) then
        raise exception 'Persistence migration stopped: public.add_xp has another signature; inspect it before migration';
    end if;
    if target_oid is not null then
        select proargnames into arg_names from pg_proc where oid = target_oid;
        if arg_names[1:3] is distinct from array['p_user_id', 'p_username', 'p_amount'] then
            raise exception 'Persistence migration stopped: add_xp parameter names differ from the bot RPC contract';
        end if;
    end if;
end;
$$;

create or replace function public.add_xp(
    p_user_id bigint,
    p_username text,
    p_amount integer
)
returns void
language sql
security definer
set search_path = pg_catalog, public
as $$
    insert into public.profiles (user_id, username, xp)
    values (p_user_id, p_username, p_amount)
    on conflict (user_id) do update
       set xp = public.profiles.xp + excluded.xp,
           username = coalesce(excluded.username, public.profiles.username),
           updated_at = now();
$$;

alter function public.add_xp(bigint, text, integer) owner to postgres;
revoke all on function public.add_xp(bigint, text, integer) from public, anon, authenticated;
grant execute on function public.add_xp(bigint, text, integer) to service_role;

notify pgrst, 'reload schema';
